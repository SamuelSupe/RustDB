SELECT TIMESTAMP '2024-02-29 12:34:56.123456' AS typed_literal,
       CAST('2024-02-29 12:34:56.654321' AS TIMESTAMP) AS string_cast,
       CAST(DATE '2024-02-29' AS TIMESTAMP) AS date_cast,
       CAST(TIMESTAMP '2024-02-29 23:59:59.999999' AS DATE) AS timestamp_date,
       CAST(TIMESTAMP '2024-02-29 12:34:56.120000' AS VARCHAR) AS timestamp_text,
       TIMESTAMP '2024-01-31 12:34:56.123456' + INTERVAL '1' MONTH AS plus_month,
       TIMESTAMP '2024-02-29 12:34:56.123456' - INTERVAL '1' YEAR AS minus_year,
       TIMESTAMP '2024-02-29 12:34:56.123456' + INTERVAL '2' DAY AS plus_days;
